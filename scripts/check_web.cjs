const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1050}});
    const errors=[];
    page.on('pageerror', error=>errors.push(error.message));
    await page.goto('http://127.0.0.1:8765');
    await page.waitForSelector('.stat-value');
    const snapshot = await (await page.request.get('http://127.0.0.1:8765/api/data')).json();
    assert.equal(await page.locator('.stat-value').first().textContent(),String(snapshot.summary.documents));
    await page.screenshot({path:'/tmp/research-desktop.png',fullPage:true});
    await page.getByRole('link',{name:/Dokumentumtár/}).click();
    await page.locator('#query').fill('nemlétező dokumentum');
    await page.getByText('Nincs a feltételeknek megfelelő dokumentum.').waitFor();
    await page.locator('#query').fill('');
    await page.locator('#filter').selectOption('KSH');
    assert.equal(await page.locator('tbody tr').count(),24);
    await page.locator('[data-document]').first().click();
    await page.waitForSelector('.detail-text');
    assert.ok((await page.locator('.detail-text').textContent()).length>30);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('dialog').isVisible(),false);
    await page.getByRole('link',{name:'◇ Bizonyítékok'}).click();
    await page.waitForSelector('.evidence-card');
    await page.locator('#query').fill('adminisztráció');
    assert.ok(await page.locator('.evidence-card').count()>0);
    await page.getByRole('link',{name:'◎ Forrásjegyzék'}).click();
    await page.getByRole('heading',{name:'Auditált források'}).waitFor();
    assert.equal(await page.locator('tbody tr').count(),snapshot.sources.length);
    await page.getByRole('heading',{name:'Tapasztalatok ellenőrzési naplója'}).waitFor();
    const report = await page.request.get('http://127.0.0.1:8765/api/report');
    assert.equal(report.status(),200);
    assert.match(report.headers()['content-disposition'],/attachment/);
    const denied = await page.request.get('http://127.0.0.1:8765/api/data',{headers:{Host:'untrusted.example'}});
    assert.equal(denied.status(),403);
    assert.equal((await page.request.post('http://127.0.0.1:8765/api/data',{data:{}})).status(),501);
    await page.setViewportSize({width:390,height:844});
    await page.locator('nav [data-page=overview]').click();
    await page.waitForSelector('.stats');
    await page.screenshot({path:'/tmp/research-mobile.png',fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.route('**/api/data', route=>route.fulfill({status:500,body:'{}'}));
    await page.getByRole('button',{name:'↻ Adatok frissítése'}).click();
    await page.getByText('Az adatbázis nem érhető el.',{exact:false}).waitFor();
    await page.unroute('**/api/data');
    await page.getByRole('button',{name:'↻ Adatok frissítése'}).click();
    await page.waitForFunction(()=>document.querySelector('#notice').textContent==='');
    assert.deepEqual(errors,[]);
    console.log('Browser checks passed: navigation, search, filter, details, downloads, read-only HTTP, mobile, error recovery.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1)});
